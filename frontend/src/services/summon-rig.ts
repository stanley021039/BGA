const pathOf = (points: readonly Point[]) =>
  'M' + points.map(([x, y]) => x + ' ' + y).join('L') + 'Z';
export function summonArmor(effect: string) {
  return (armor[effect] || []).map(pathOf);
}
export function summonRig(effect: string) {
  const rig = rigs[effect];
  return rig?.parts.map((points, index) => ({
    path: pathOf(points),
    clip: 'polygon(' + points.map(([x, y]) => `${x * 100}% ${y * 100}%`).join(',') + ')',
    origin: `${rig.joints[index][0] * 100}% ${rig.joints[index][1] * 100}%`,
  }));
}
